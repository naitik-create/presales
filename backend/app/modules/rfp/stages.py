HOW = {"ok": "Generated by AI", "edited": "Edited", "revised": "Revised by AI on request", "restored": "Restored"}
MAX_COMPLIANCE_REVISE = 30


def latest(db: Session, wid: int, agent_key: str) -> RFPAgentRun | None:
    return db.scalar(select(RFPAgentRun).where(RFPAgentRun.workspace_id == wid, RFPAgentRun.agent_key == agent_key)
                     .order_by(RFPAgentRun.id.desc()))


def content(run: RFPAgentRun) -> dict:
    return run.edited_output or run.output


# ---------- state: who approved, what needs review ----------
def _state_row(db: Session, wid: int) -> RFPAgentRun:
    row = latest(db, wid, W.STATE_KEY)
    if row is None:
        row = RFPAgentRun(workspace_id=wid, agent_key=W.STATE_KEY, output={"approved": {}, "needs_review": {}})
        db.add(row)
        db.flush()
    return row


def get_state(db: Session, wid: int) -> dict:
    row = latest(db, wid, W.STATE_KEY)
    out = dict(row.output) if row else {}
    return {"approved": dict(out.get("approved") or {}), "needs_review": dict(out.get("needs_review") or {})}


def _update_state(db: Session, wid: int, fn) -> None:
    row = _state_row(db, wid)
    data = {"approved": dict((row.output or {}).get("approved") or {}),
            "needs_review": dict((row.output or {}).get("needs_review") or {})}
    fn(data)
    row.output = data  # a new dict, so the JSONB change is saved


def reset_state(db: Session, wid: int) -> None:
    _update_state(db, wid, lambda s: (s["approved"].clear(), s["needs_review"].clear()))


def flag(db: Session, wid: int, stages: list[str], why: str) -> None:
    def f(s):
        for k in stages:
            s["needs_review"][k] = why
    _update_state(db, wid, f)


# ---------- versions ----------
def new_version(db: Session, ws: RFPWorkspace, agent_key: str, data: dict, how: str) -> RFPAgentRun:
    run = RFPAgentRun(workspace_id=ws.id, agent_key=agent_key, revision=ws.revision, output=data, status=how, approved=False)
    db.add(run)
    db.flush()
    return run


def versions(db: Session, wid: int, agent_key: str) -> list[dict]:
    runs = db.scalars(select(RFPAgentRun).where(RFPAgentRun.workspace_id == wid, RFPAgentRun.agent_key == agent_key)
                      .order_by(RFPAgentRun.id.desc()).limit(40)).all()
    total = len(runs)
    return [{"id": r.id, "version": total - i, "at": r.at, "how": HOW.get(r.status, r.status), "revision": r.revision,
             "approved": r.approved, "current": i == 0} for i, r in enumerate(runs)]


# ---------- approval ----------
def compliance_summary(db: Session, wid: int) -> dict:
    rows = db.execute(select(RFPRequirement.id, RFPComplianceResponse.status, RFPComplianceResponse.approved,
                             RFPComplianceResponse.origin, RFPComplianceResponse.origin_detail)
                      .outerjoin(RFPComplianceResponse, RFPComplianceResponse.requirement_id == RFPRequirement.id)
                      .where(RFPRequirement.workspace_id == wid, RFPRequirement.active.is_(True))).all()
    by_status: dict[str, int] = {}
    for r in rows:
        if r.status:
            by_status[r.status] = by_status.get(r.status, 0) + 1
    return {"total": len(rows), "answered": sum(1 for r in rows if r.status),
            "approved": sum(1 for r in rows if r.approved), "by_status": by_status,
            "from_past_rfps": sum(1 for r in rows if (r.origin_detail or {}).get("reused_from")),
            "only_past_rfps": sum(1 for r in rows if r.origin == "submitted_rfp")}


def _stage_run(db: Session, wid: int, key: str) -> RFPAgentRun | None:
    agent = W.BY_KEY[key]["agent"]
    return latest(db, wid, agent) if agent else None


def is_approved(db: Session, wid: int, key: str) -> bool:
    if key == "compliance":
        s = compliance_summary(db, wid)
        return s["total"] > 0 and s["approved"] == s["total"]
    run = _stage_run(db, wid, key)
    return bool(run and run.approved)


def approve(db: Session, ws: RFPWorkspace, key: str, by: str, user_id: int | None) -> None:
    """Approve a step. Raises ValueError with a message for the user when it cannot be approved yet."""
    pending = [W.BY_KEY[d]["label"] for d in W.BY_KEY[key]["depends"] if not is_approved(db, ws.id, d)]
    if pending:
        raise ValueError(f"Approve {' and '.join(pending)} first.")
    if key == "compliance":
        rows = db.scalars(select(RFPComplianceResponse)
                          .join(RFPRequirement, RFPRequirement.id == RFPComplianceResponse.requirement_id)
                          .where(RFPRequirement.workspace_id == ws.id, RFPRequirement.active.is_(True))).all()
        total = db.scalar(select(func.count()).select_from(RFPRequirement)
                          .where(RFPRequirement.workspace_id == ws.id, RFPRequirement.active.is_(True))) or 0
        if not total or len(rows) < total:
            raise ValueError("Every requirement needs an answer before the compliance step can be approved.")
        now = utcnow()
        for c in rows:
            if not c.approved:
                c.approved, c.approved_by, c.approved_at = True, user_id, now
    else:
        run = _stage_run(db, ws.id, key)
        if not run:
            raise ValueError(f"{W.BY_KEY[key]['label']} has not been generated yet.")
        if key == "boq":
            problems = [w for w in bidparams.warnings(run.output["params"]) if "will not be quoted" not in w]
            if problems:
                raise ValueError("Fix before approving: " + " ".join(problems))
            run.at = utcnow()
        run.approved = True

    def f(s):
        s["approved"][key] = {"by": by, "at": utcnow().isoformat()}
        s["needs_review"].pop(key, None)
    _update_state(db, ws.id, f)


def reopen(db: Session, ws: RFPWorkspace, key: str, by: str) -> list[str]:
    if key == "compliance":
        raise ValueError("Withdraw approval on the individual answers you want to change.")
    run = _stage_run(db, ws.id, key)
    if run:
        run.approved = False
    _update_state(db, ws.id, lambda s: s["approved"].pop(key, None))
    return changed(db, ws, key, f"{W.BY_KEY[key]['label']} was reopened by {by}")


def changed(db: Session, ws: RFPWorkspace, key: str, why: str) -> list[str]:
    """`key` has new content or was reopened: reopen the approved steps that depend on it and say why."""
    hit = []
    for d in W.downstream(key):
        if d == "compliance":
            continue
        run = _stage_run(db, ws.id, d)
        if run and run.approved:
            run.approved = False
            hit.append(d)
    if hit:
        def f(s):
            for d in hit:
                s["needs_review"][d] = why
                s["approved"].pop(d, None)
        _update_state(db, ws.id, f)
    return hit


# ---------- overview for the review screen ----------
def overview(db: Session, ws: RFPWorkspace) -> dict:
    state = get_state(db, ws.id)
    comp = compliance_summary(db, ws.id)
    has_analysis = latest(db, ws.id, "analysis") is not None
    out = []
    for s in W.STAGES:
        key = s["key"]
        run = _stage_run(db, ws.id, key)
        approved = is_approved(db, ws.id, key)
        if key == "compliance":
            exists = comp["total"] > 0
        elif key == "boq":
            exists = run is not None or has_analysis
        else:
            exists = run is not None
        inputs_changed = []
        if run and not approved:
            for d in s["depends"]:
                dr = _stage_run(db, ws.id, d)
                if dr and dr.id > run.id:  # the step it is built from changed after this version was made
                    inputs_changed.append(W.BY_KEY[d]["label"])
        draft = latest(db, ws.id, W.DRAFT_PREFIX + key)
        status = ("approved" if approved else "needs_review" if key in state["needs_review"]
                  else "to_review" if exists else "not_run")
        out.append({
            "key": key, "label": s["label"], "status": status, "reason": state["needs_review"].get(key, ""),
            "approved_by": (state["approved"].get(key) or {}).get("by", "") if approved else "",
            "approved_at": (state["approved"].get(key) or {}).get("at") if approved else None,
            "run_id": run.id if run else None, "at": run.at if run else None,
            "how": ("Saved" if key == "boq" else HOW.get(run.status, run.status)) if run else "",
            "versions": db.scalar(select(func.count()).select_from(RFPAgentRun).where(
                RFPAgentRun.workspace_id == ws.id, RFPAgentRun.agent_key == s["agent"])) if s["agent"] else 0,
            "depends_on": [W.BY_KEY[d]["label"] for d in s["depends"]],
            "blocked_by": [W.BY_KEY[d]["label"] for d in s["depends"] if not is_approved(db, ws.id, d)],
            "inputs_changed": inputs_changed,
            "downloads": [{"kind": k, "label": lbl} for k, lbl in s["downloads"]],
            "can_revise": key in W.REVISABLE,
            "draft": None if not draft else {"id": draft.id, "at": draft.at, **{
                k: draft.output.get(k) for k in ("instruction", "by", "changes", "answers")},
                "outdated": key in W.DOC_STAGES and run is not None and draft.output.get("base_run_id") != run.id},
        })
    return {"stages": out, "compliance": comp}


def export_blocked(db: Session, wid: int, kind: str) -> str | None:
    stage = W.EXPORT_STAGE.get(kind)
    if stage and not is_approved(db, wid, stage):
        return f"Approve the {W.BY_KEY[stage]['label']} step first; its downloads open once it is approved."
    return None


# ---------- AI revision ----------
def _facts_obj(facts) -> dict:
    """bid_facts are stored as a labelled list; the analysis schema has them as an object."""
    if isinstance(facts, dict):
        return facts
    by_label = {f.get("item"): f for f in facts or []}
    return {key: {"value": (by_label.get(label) or {}).get("value", bidpack.NOT_STATED),
                  "ref": (by_label.get(label) or {}).get("ref", "")} for key, label in bidpack.BID_FACTS}


def _for_ai(stage: str, current: dict) -> dict:
    data = {k: v for k, v in current.items() if k not in ("citations", "owner_counts") and not k.startswith("_")}
    if stage == "synopsis":
        data["bid_facts"] = _facts_obj(data.get("bid_facts"))
    if stage == "scope":
        data.pop("matrix", None)
    return data


def _scope_listing(db: Session, ws: RFPWorkspace, current: dict) -> str:
    by_no = {m["number"]: m for m in current.get("matrix") or []}
    rows = db.execute(select(RFPRequirement, RFPComplianceResponse)
                      .outerjoin(RFPComplianceResponse, RFPComplianceResponse.requirement_id == RFPRequirement.id)
                      .where(RFPRequirement.workspace_id == ws.id, RFPRequirement.active.is_(True))
                      .order_by(RFPRequirement.id)).all()
    lines = []
    for r, c in rows:
        m = by_no.get(r.number, {})
        lines.append(f"{r.number} | {r.source_ref} | {' '.join(r.text.split())[:300]} | {c.status if c else 'pending'}"
                     f" | owner={m.get('owner', '')} | product={m.get('product', '')} | module={m.get('module', '')}"
                     f" | note={m.get('note', '')}")
    return "\n".join(lines)


def _revise_doc(db: Session, ws: RFPWorkspace, stage: str, instruction: str, job: Job) -> dict:
    from app.modules.rfp import service  # service imports nothing from here; avoid a cycle at import time
    agent = W.BY_KEY[stage]["agent"]
    run = latest(db, ws.id, agent)
    if not run:
        raise ValueError(f"{W.BY_KEY[stage]['label']} has not been generated yet")
    current = content(run)
    agent_key, schema, system, _kb = A.DOC_AGENTS[agent]
    sys = A.REVISE_SYSTEM + system
    if stage == "scope":
        schema, sys = A.SCOPE_REVISE_SCHEMA, sys + "\n\n" + A.SCOPE_REVISE_NOTE
        material = f"<requirements>\n{_scope_listing(db, ws, current)}\n</requirements>"
    elif stage == "considerations":
        material = service.considerations_material(db, ws)
    else:
        material = service.full_text(db, ws)[0]
    user = (f"<current_content>\n{json.dumps(_for_ai(stage, current), ensure_ascii=False, default=str)}\n</current_content>\n"
            f"<instruction>\n{instruction}\n</instruction>\n<material>\n{material}\n</material>")
    out = ai.call(db, agent_key, system=sys, user=user, schema=schema, user_id=job.created_by,
                  ref_type="rfp_workspace", ref_id=ws.id, job_id=job.id)
    proposal = W.apply_revision(stage, current, out)
    return {"proposal": proposal, "base_run_id": run.id, "changes": W.diff(current, proposal)}


def _answer(c: RFPComplianceResponse | None) -> dict:
    return {k: (getattr(c, k) if c else "") for k in ("status", "response", "explanation", "evidence", "validation_remarks")}


def _revise_compliance(db: Session, ws: RFPWorkspace, ids: list[int], instruction: str, job: Job) -> dict:
    from app.modules.rfp import service
    reqs = list(db.scalars(select(RFPRequirement).where(RFPRequirement.workspace_id == ws.id,
                                                        RFPRequirement.id.in_(ids)).order_by(RFPRequirement.id)))
    answers = []
    for i in range(0, len(reqs), 6):
        batch = reqs[i:i + 6]
        parts, lookup, current = [], {}, {}
        for r in batch:
            hits, past = service._evidence_for(db, r, f"R{r.id}-")
            lookup[str(r.id)] = (hits, past)
            c = db.scalar(select(RFPComplianceResponse).where(RFPComplianceResponse.requirement_id == r.id))
            current[str(r.id)] = c
            p = "\n".join(f'<source id="{x.id}" title="Past answer: {x.customer} {x.submitted_on} v{x.product_version}">'
                          f"Requirement: {x.requirement}\nStatus: {x.status}\nResponse: {x.response}</source>" for x in past)
            parts.append(f'<requirement id="{r.id}" ref="{r.source_file} {r.source_ref}">{r.text}</requirement>\n'
                         f"<current_answer>{json.dumps(_answer(c), ensure_ascii=False)}</current_answer>\n"
                         f"<sources>\n{retrieval.format_hits(hits)}\n{p}\n</sources>")
        out = ai.call(db, "technical_compliance", system=A.COMPLIANCE_SYSTEM + "\n\n" + A.COMPLIANCE_REVISE_NOTE,
                      user="\n\n".join(parts) + f"\n\n<instruction>\n{instruction}\n</instruction>",
                      schema=A.COMPLIANCE_SCHEMA, user_id=job.created_by, ref_type="rfp_workspace", ref_id=ws.id,
                      job_id=job.id)
        by_id = {str(r.id): r for r in batch}
        for a in out["answers"]:
            r = by_id.get(a["requirement_id"])
            if not r:
                continue
            hits, past = lookup[str(r.id)]
            answers.append({"requirement_id": r.id, "number": r.number, "text": r.text[:400],
                            "before": _answer(current[str(r.id)]), "after": service.answer_values(a, hits, past)})
    return {"answers": answers}


@handler("rfp.revise")
def revise_job(db: Session, job: Job, ctx: JobContext) -> dict:
    ws = db.get(RFPWorkspace, job.payload["workspace_id"])
    stage, instruction = job.payload["stage"], job.payload["instruction"]
    ctx.progress(10, f"Revising {W.BY_KEY[stage]['label']}")
    if stage == "compliance":
        result = _revise_compliance(db, ws, job.payload.get("requirement_ids") or [], instruction, job)
    else:
        result = _revise_doc(db, ws, stage, instruction, job)
    db.execute(delete(RFPAgentRun).where(RFPAgentRun.workspace_id == ws.id,
                                         RFPAgentRun.agent_key == W.DRAFT_PREFIX + stage))
    db.add(RFPAgentRun(workspace_id=ws.id, agent_key=W.DRAFT_PREFIX + stage, revision=ws.revision, job_id=job.id,
                       output={**result, "instruction": instruction, "by": job.payload.get("by", "")}))
    db.commit()
    return {"stage": stage}


def drop_draft(db: Session, wid: int, stage: str) -> RFPAgentRun | None:
    d = latest(db, wid, W.DRAFT_PREFIX + stage)
    if d:
        db.delete(d)
    return d
